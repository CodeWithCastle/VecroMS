/**
 * VecroMS Design System — token build
 *
 * Reads tokens/tokens.json (the single source of truth) and generates:
 *   - tokens/tokens.css          CSS custom properties, light + dark
 *   - tokens/tailwind.preset.js  Tailwind theme adapter
 *
 * Run from anywhere:
 *   node design-system/tokens/build.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));

const HEADER = `/* ============================================================
   VecroMS Design System — generated tokens
   Source: tokens.json · Build: node tokens/build.mjs
   Do not edit this file by hand. Edit tokens.json instead.
   ============================================================ */`;

/* ------------------------------------------------------------------ */
/* CSS                                                                 */
/* ------------------------------------------------------------------ */

const light = [];
const dark = [];
const root = [];

const add = (arr, name, value) => arr.push(`  --${name}: ${value};`);
const section = (arr, title) => arr.push(`\n  /* ${title} */`);

/* Primitives */
section(root, "Color · brand");
for (const [name, scale] of Object.entries(tokens.color.brand)) {
  for (const [step, value] of Object.entries(scale)) {
    add(root, `vms-color-brand-${name}-${step}`, value);
  }
}
section(root, "Color · neutral");
for (const [step, value] of Object.entries(tokens.color.neutral)) {
  add(root, `vms-color-neutral-${step}`, value);
}
section(root, "Color · navy");
for (const [step, value] of Object.entries(tokens.color.navy)) {
  add(root, `vms-color-navy-${step}`, value);
}

/* Semantic surfaces */
function surfaceVars(target, theme) {
  const map = {
    canvas: "bg-canvas",
    default: "bg-surface",
    subtle: "bg-surface-subtle",
    sunken: "bg-surface-sunken",
    hover: "bg-surface-hover",
    raised: "bg-surface-raised",
    inverse: "bg-inverse",
    overlay: "bg-overlay",
  };
  for (const [key, name] of Object.entries(map)) {
    const value = tokens.color.surface[theme][key];
    if (value) add(target, `vms-${name}`, value);
  }
}

function textVars(target, theme) {
  for (const [key, value] of Object.entries(tokens.color.text[theme])) {
    add(target, `vms-text-${key}`, value);
  }
}

function borderVars(target, theme) {
  for (const [key, value] of Object.entries(tokens.color.border[theme])) {
    add(target, `vms-border-${key}`, value);
  }
}

function primaryVars(target, theme) {
  const p = tokens.color.primary[theme];
  add(target, "vms-primary", p.default);
  add(target, "vms-primary-hover", p.hover);
  add(target, "vms-primary-active", p.active);
  add(target, "vms-primary-subtle", p.subtle);
  add(target, "vms-primary-subtle-hover", p["subtle-hover"]);
  add(target, "vms-primary-fg", p.fg);
  add(target, "vms-primary-fg-subtle", p["fg-subtle"]);
}

function statusVars(target, theme) {
  for (const [name, roles] of Object.entries(tokens.color.status[theme])) {
    for (const [role, value] of Object.entries(roles)) {
      add(target, `vms-${name}-${role}`, value);
    }
  }
}

function chartVars(target, theme) {
  tokens.color.chart[theme].forEach((value, i) => {
    add(target, `vms-chart-${i + 1}`, value);
  });
}

section(root, "Semantic · light");
surfaceVars(root, "light");
textVars(root, "light");
borderVars(root, "light");
primaryVars(root, "light");
statusVars(root, "light");
chartVars(root, "light");

section(dark, "Semantic · dark");
surfaceVars(dark, "dark");
textVars(dark, "dark");
borderVars(dark, "dark");
primaryVars(dark, "dark");
statusVars(dark, "dark");
chartVars(dark, "dark");
add(dark, "vms-shadow-focus", tokens.shadow["focus-dark"]);

/* Typography */
section(root, "Typography · families");
add(root, "vms-font-sans", tokens.typography.family.sans);
add(root, "vms-font-mono", tokens.typography.family.mono);

section(root, "Typography · weights");
for (const [key, value] of Object.entries(tokens.typography.weight)) {
  add(root, `vms-weight-${key}`, value);
}

section(root, "Typography · scale");
for (const [key, value] of Object.entries(tokens.typography.size)) {
  add(root, `vms-font-size-${key}`, value.fontSize);
  add(root, `vms-line-height-${key}`, value.lineHeight);
  add(root, `vms-letter-spacing-${key}`, value.letterSpacing);
  add(root, `vms-font-weight-${key}`, value.fontWeight);
  if (value.textTransform) add(root, `vms-text-transform-${key}`, value.textTransform);
}

/* Space */
section(root, "Space · 4px base");
for (const [key, value] of Object.entries(tokens.space)) {
  add(root, `vms-space-${key}`, value);
}

/* Radius */
section(root, "Radius");
for (const [key, value] of Object.entries(tokens.radius)) {
  add(root, `vms-radius-${key}`, value);
}

/* Shadow */
section(root, "Elevation");
for (const [key, value] of Object.entries(tokens.shadow)) {
  add(root, `vms-shadow-${key}`, value);
}

/* Border widths */
section(root, "Border widths");
for (const [key, value] of Object.entries(tokens.borderWidth)) {
  add(root, `vms-border-width-${key}`, value);
}

/* Sizes */
section(root, "Sizing");
for (const [group, scale] of Object.entries(tokens.size)) {
  if (typeof scale === "string") {
    add(root, `vms-size-${group}`, scale);
    continue;
  }
  for (const [key, value] of Object.entries(scale)) {
    add(root, `vms-size-${group}-${key}`, value);
  }
}

/* Motion */
section(root, "Motion");
for (const [key, value] of Object.entries(tokens.motion.duration)) {
  add(root, `vms-duration-${key}`, value);
}
for (const [key, value] of Object.entries(tokens.motion.easing)) {
  add(root, `vms-ease-${key}`, value);
}

/* Breakpoints */
section(root, "Breakpoints");
for (const [key, value] of Object.entries(tokens.breakpoint)) {
  add(root, `vms-bp-${key}`, value);
}

/* Z-index */
section(root, "Z-index");
for (const [key, value] of Object.entries(tokens.z)) {
  add(root, `vms-z-${key}`, value);
}

/* Component tokens */
section(root, "Component · buttons");
for (const [key, value] of Object.entries(tokens.component.button)) {
  add(root, `vms-button-${key}`, value);
}
section(root, "Component · inputs");
for (const [key, value] of Object.entries(tokens.component.input)) {
  add(root, `vms-input-${key}`, value);
}
section(root, "Component · cards");
for (const [key, value] of Object.entries(tokens.component.card)) {
  add(root, `vms-card-${key}`, value);
}
section(root, "Component · badges");
for (const [key, value] of Object.entries(tokens.component.badge)) {
  add(root, `vms-badge-${key}`, value);
}
section(root, "Component · tables");
for (const [key, value] of Object.entries(tokens.component.table)) {
  add(root, `vms-table-${key}`, value);
}
section(root, "Component · modals");
for (const [key, value] of Object.entries(tokens.component.modal)) {
  add(root, `vms-modal-${key}`, value);
}

const css = `${HEADER}

:root {
  color-scheme: light;
${root.join("\n")}
}

[data-theme="dark"] {
  color-scheme: dark;
${dark.join("\n")}
}

/* Follow the OS preference unless a theme is pinned on <html>. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${dark.map((line) => `  ${line}`).join("\n")}
  }
}
`;

writeFileSync(join(here, "tokens.css"), css, "utf8");

/* ------------------------------------------------------------------ */
/* Tailwind preset                                                     */
/* ------------------------------------------------------------------ */

const statusColor = (name) => {
  const roles = tokens.color.status.light[name];
  const color = {
    DEFAULT: roles["solid-strong"]
      ? `var(--vms-${name}-solid-strong)`
      : `var(--vms-${name}-solid)`,
    solid: `var(--vms-${name}-solid)`,
    bg: `var(--vms-${name}-bg)`,
    border: `var(--vms-${name}-border)`,
    fg: `var(--vms-${name}-fg)`,
  };
  if (roles["solid-strong"]) color["solid-strong"] = `var(--vms-${name}-solid-strong)`;
  return color;
};

const flatHeight = Object.fromEntries(
  Object.entries(tokens.size.control).map(([k, v]) => [`control-${k}`, v]),
);
const flatWidth = Object.fromEntries([
  ...Object.entries(tokens.size.sidebar).map(([k, v]) => [`sidebar-${k}`, v]),
  ["topbar", tokens.size.topbar],
]);

const fontSize = Object.fromEntries(
  Object.entries(tokens.typography.size).map(([key, value]) => [
    key,
    [
      value.fontSize,
      {
        lineHeight: value.lineHeight,
        letterSpacing: value.letterSpacing,
        fontWeight: String(value.fontWeight),
      },
    ],
  ]),
);

